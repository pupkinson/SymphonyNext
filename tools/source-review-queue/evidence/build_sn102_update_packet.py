"""Offline packager; no root/service/API/model operations.

Usage: python3 -B build_sn102_update_packet.py SOURCE OUTPUT PREDECESSOR INPUTS
INPUTS must contain the published, exact-head independent-review.json receipt
and source-attestation.json, plus qualification logs. OUTPUT must be new.
No receipt is generated by this script and no installation is authorized.
"""
import gzip
import hashlib
import importlib.util
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tarfile


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def save(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + '\n')


def build(source, output, previous, inputs):
    def git(value):
        return subprocess.check_output(['git', '-C', str(source), 'rev-parse', value]).decode().strip()
    head, tree = git('HEAD'), git('HEAD^{tree}')
    review = json.loads((inputs / 'independent-review.json').read_bytes())
    assert review['head'] == head and review['tree'] == tree
    assert review['independent'] is True and review['state'] == 'completed'
    assert review['result'] == 'no_major_findings'
    assert review['conditions'] == {'4285700019': 'PASS', '4281361556': 'PASS', '4281361568': 'PASS'}
    assert re.fullmatch(r'https://github\.com/pupkinson/SymphonyNext/pull/103#issuecomment-[0-9]+', review['url'])
    assert sha((inputs / 'independent-review.md').read_bytes()) == review['report_sha256']
    attestation = json.loads((inputs / 'source-attestation.json').read_bytes())
    assert attestation['head'] == head and attestation['tree'] == tree
    for name, expected in attestation['source_sha256'].items():
        assert sha((source / name).read_bytes()) == expected, name
    base = source / 'tools/source-review-queue'
    spec = importlib.util.spec_from_file_location('reviewed_updater', base / 'update_queue.py')
    u = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(u)
    prior = {name: (previous / name).read_bytes() for name in u.PREDECESSOR}
    assert {name: sha(raw) for name, raw in prior.items()} == u.PREDECESSOR
    output.mkdir(mode=0o700)  # Never overwrite a previous or blocked packet.
    packet = output / 'package'
    packet.mkdir(mode=0o700)
    (packet / 'payload').mkdir(mode=0o700)
    payload = {name: (base / 'candidate' / name).read_bytes() for name in ('queue.py', 'execution.py')}
    metadata = json.loads(prior['installed.json'])
    metadata.update(script_sha256=sha(payload['queue.py']), execution_schema='snq-execution-install/v1',
                    execution_sha256=sha(payload['execution.py']))
    payload['installed.json'] = (json.dumps(metadata, sort_keys=True, indent=2) + '\n').encode()
    payload['executor-policy.json'] = (json.dumps(dict(schema='snq-executor-policy/v1', enabled=False,
        revision='not-admitted', tasks={}), sort_keys=True, indent=2) + '\n').encode()
    for name, raw in payload.items():
        (packet / 'payload' / name).write_bytes(raw)
    shutil.copyfile(base / 'update_queue.py', packet / 'update_queue.py')
    manifest = dict(schema='snq-update-package/v1', head=head, tree=tree, predecessor=u.PREDECESSOR,
                    payload={name: sha(raw) for name, raw in payload.items()},
                    updater_sha256=sha((packet / 'update_queue.py').read_bytes()), review=review)
    save(packet / 'manifest.json', manifest)
    for name in ('UPDATE.md', 'evidence/gh102-notification-journals.md'):
        shutil.copyfile(base / name, packet / Path(name).name)
    shutil.copytree(inputs, packet / 'qualification')
    static = packet / 'qualification/predecessor'
    static.mkdir(mode=0o700)
    for name, raw in prior.items():
        (static / name).write_bytes(raw)

    # Real predecessor bytes, real journals, exact real manifest; systemd only
    # is an explicit test double. No surrogate review is used in this packet.
    sys.path.insert(0, str(base / 'tests'))
    import test_queue_updater as fixtures
    f = fixtures.UpdateTests('test_check_is_read_only_and_apply_keeps_workflow_state_and_execution_disabled')
    f.setUp()
    try:
        for name, raw in prior.items():
            (f.install / name).write_bytes(raw)
        (f.install / 'queue.py').chmod(0o755)
        shutil.copytree(packet, f.package, dirs_exist_ok=True)
        update = u.Updater(f.package, f.install, f.state, f.ctl, owner_uid=os.geteuid(), drain_seconds=0)
        before = f.state_bytes()
        checked = update.check()
        applied = update.apply()
        repeated_apply = update.apply()
        rolled = update.rollback()
        repeated_rollback = update.rollback()
        assert f.state_bytes() == before
        assert all((f.install / name).read_bytes() == raw for name, raw in prior.items())
        assert not (f.install / 'execution.py').exists() and not (f.install / 'executor-policy.json').exists()
        events = f.ctl.events[:]
    finally:
        f.doCleanups()
    save(packet / 'qualification/actual-byte-roundtrip.json', dict(head=head, tree=tree,
         check=checked, apply=applied, repeat_apply=repeated_apply, rollback=rolled,
         repeat_rollback=repeated_rollback, events=events, state_bytes_preserved=True,
         actual_predecessor_bytes_restored=True, systemd='TEST_DOUBLE_NOT_NATIVE',
         review='ACTUAL_INDEPENDENT_EXACT_HEAD_RECEIPT', root_update='NOT_RUN',
         native_rollback='NOT_RUN', live_pilot='NOT_RUN', model_turns=0))
    (packet / 'ROOT-PACKAGE-STATUS.md').write_text(
        '# Source reviewed; NOT INSTALLED\n\n'
        + f'HEAD `{head}`, TREE `{tree}`.\n\n'
        + 'Independent exact-head report and explicit three-P1 verdicts are in qualification.\n'
        + 'Only the exact four-file7fa0ee predecessor is supported. Disabled executor policy.\n'
        + 'Offline actual-byte check/apply/repeat/rollback/repeat passed with a systemd double.\n'
        + 'This is not a native transition, native rollback, live pilot or owner install admission.\n'
        + 'Verify fresh host/service/static/journal readback and outer archive hash before root use.\n'
        + 'Never restore old state, replay unknown notifications or discard blocked archives.\n')
    files = sorted(p for p in packet.rglob('*') if p.is_file())
    assert not any(p.is_symlink() for p in packet.rglob('*'))
    (packet / 'SHA256SUMS').write_text(''.join(sha(p.read_bytes()) + '  ' + p.relative_to(packet).as_posix() + '\n'
                                             for p in files))
    archive = output / ('sn102-' + head[:12] + '-source-reviewed.tar.gz')
    with archive.open('xb') as out:
        with gzip.GzipFile(filename='', mode='wb', fileobj=out, mtime=0) as gz:
            with tarfile.open(fileobj=gz, mode='w', format=tarfile.PAX_FORMAT) as tf:
                for path in sorted(p for p in packet.rglob('*') if p.is_file()):
                    raw = path.read_bytes()
                    item = tarfile.TarInfo('package/' + path.relative_to(packet).as_posix())
                    item.size, item.mode, item.uid, item.gid, item.mtime = len(raw), 0o600, 0, 0, 0
                    tf.addfile(item, io.BytesIO(raw))
    with tarfile.open(archive, 'r:gz') as tf:
        members = tf.getmembers()
        assert all(m.isfile() and m.name.startswith('package/') and '..' not in Path(m.name).parts for m in members)
        assert len({m.name for m in members}) == len(members)
        for member in members:
            assert tf.extractfile(member).read() == (output / member.name).read_bytes()
    receipt = dict(head=head, tree=tree, archive=str(archive), bytes=archive.stat().st_size,
                   sha256=sha(archive.read_bytes()), members=len(members), members_readback_match=True,
                   source_review=review['url'], status='SOURCE_REVIEWED_NOT_INSTALLED',
                   native_update='NOT_RUN', native_rollback='NOT_RUN', live_pilot='NOT_RUN')
    save(output / 'package-receipt.json', receipt)
    return receipt


if __name__ == '__main__':
    print(json.dumps(build(*map(lambda x: Path(x).resolve(), sys.argv[1:5])), sort_keys=True))
